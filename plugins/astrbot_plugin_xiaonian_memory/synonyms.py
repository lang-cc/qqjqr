    ("吃饭", "干饭", "外卖", "饭", "饿", "宵夜", "馋"),
    ("酒", "啤酒", "白酒", "喝点", "微醺"),
    ("好吃的", "好吃", "好喝", "香", "馋"),
    # 身体状态
    ("累", "困", "疲惫", "撑不住", "乏", "没劲"),
    ("睡", "睡觉", "失眠", "熬夜", "早睡", "睡不着", "醒了"),
    ("生病", "感冒", "发烧", "难受", "疼", "不舒服"),
    # 钱与工作
    ("钱", "工资", "花销", "穷", "月光", "开销", "省着"),
